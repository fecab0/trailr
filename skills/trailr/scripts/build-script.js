#!/usr/bin/env node
'use strict';
// script.json -> script.js (window.SCRIPT + window.TIMING) and the script table for the user.
//
//   node build-script.js <script.json> [--out script.js] [--md table.md] [--check]
//
// --check validates and prints the table without writing script.js.
// Exit code 1 on invalid input. Read-time problems are warnings (exit 0) so the user decides.
const fs = require('fs');
const path = require('path');
const { computeTiming, readTimeWarnings } = require('./lib/timeline');
const { parseArgs } = require('./lib/args');

const { pos, opt } = parseArgs(process.argv.slice(2), ['check']);
if (!pos[0]) {
  console.error('usage: node build-script.js <script.json> [--out script.js] [--md table.md] [--check]');
  process.exit(2);
}
const src = path.resolve(pos[0]);
let script;
try {
  script = JSON.parse(fs.readFileSync(src, 'utf8'));
} catch (e) {
  console.error(`Cannot read ${src}: ${e.message}`);
  process.exit(1);
}

let timing;
try {
  timing = computeTiming(script);
} catch (e) {
  console.error(`script.json: ${e.message}`);
  process.exit(1);
}

const fmt = (s) => s.toFixed(2);
const mark = { brand: 'B', user: 'U', proposal: 'P' };
const esc = (s) => String(s).replace(/\|/g, '\\|');
const rows = script.scenes.map((row, i) => {
  const s = timing.scenes[i];
  const texts = (row.text || []).map((t, j) => {
    const src = Array.isArray(row.source) ? row.source[j] : row.source;
    return `${esc(t)}${src && mark[src] ? ` [${mark[src]}]` : ''}`;
  }).join('<br>') || '—';
  const len = `${fmt(s.dur)}${s.sec != null ? ` (sec ${s.sec}${s.rounded ? ', rounded to beat' : ''})` : ` (${s.bars} bars)`}`;
  const cols = [i + 1, s.id, fmt(s.start), len, texts, esc(row.music || '—')];
  if (script.voiceover && script.voiceover.enabled) cols.push(esc(row.narration || '—'));
  return `| ${cols.join(' | ')} |`;
});
const head = ['#', 'scene', 'start s', 'length s', 'on-screen text', 'music'];
if (script.voiceover && script.voiceover.enabled) head.push('narration');
const target = script.target_sec;
const lines = [
  `Pace **${timing.pace}** · ${timing.bpm} BPM · 1 bar = ${fmt(timing.bar)} s · total **${fmt(timing.total)} s**` +
    (target ? ` (target ${target} s, ${timing.total >= target ? '+' : ''}${fmt(timing.total - target)} s)` : ''),
  '',
  `| ${head.join(' | ')} |`,
  `| ${head.map(() => '---').join(' | ')} |`,
  ...rows,
  '',
  'Text marks: [B] brand/site copy · [U] the user\'s line · [P] proposal to approve.',
];
const table = lines.join('\n');

const warnings = readTimeWarnings(script, timing);
console.log(table);
if (warnings.length) {
  console.log('\nRead-time warnings (give the scene a "sec" override or shorten the copy):');
  warnings.forEach((w) => console.log(`  - ${w}`));
}

if (opt.md) fs.writeFileSync(path.resolve(opt.md), table + '\n');
if (!opt.check) {
  const out = path.resolve(opt.out || path.join(path.dirname(src), 'script.js'));
  const body =
    '// Generated by trailr build-script.js from script.json. Do not edit: change script.json and re-run.\n' +
    `window.SCRIPT = ${JSON.stringify(script, null, 2)};\n` +
    `window.TIMING = ${JSON.stringify(timing, null, 2)};\n`;
  fs.writeFileSync(out, body);
  console.log(`\nWrote ${out}`);
}
